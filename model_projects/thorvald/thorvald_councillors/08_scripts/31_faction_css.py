"""House Thorvald's own style file UI/Styles/factions/Thorvald.css (read after the game's sheet by Quinn's hlboot
feature `faction_styles`). The game styles faction UI by class names made from the faction id (`.portrait.Corrino`,
`.box.Corrino > #background`, `.emblem.corrino`, ...); Thorvald has none, so its select card, emblems and banners are blank.

Every vanilla rule whose selector names Corrino is copied with the selector renamed to Thorvald (values untouched, so
Thorvald shows Corrino's emblem/banner art, which is what the faction row already uses), except the leader portraits,
which point at Memnon's (30_leader_card.py).

    python 31_faction_css.py <vanilla UI/style.css>   ->  04_textures/Styles/factions/Thorvald.css
(the vanilla sheet: pak_extract_one.py <game>/res.compressed.pak UI/style.css <out>)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
OUT = os.path.join(PROJ, "04_textures", "Styles", "factions", "Thorvald.css")
PORTRAIT = "UI/menu/Thorvald/box_portrait.png"

css = open(sys.argv[1], encoding="utf-8").read()
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
rules, kept, skipped = [], 0, 0
for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
    sels = [s.strip() for s in m.group(1).split(",") if s.strip()]
    mine = [s for s in sels if re.search(r"corrino", s, re.I)]
    if not mine:
        continue
    body = m.group(2).strip()
    if "portrait" in " ".join(mine) and "image:" in body and "box_portrait" in body:
        skipped += 1                                  # replaced below by Memnon's
        continue
    new = [re.sub("Corrino", "Thorvald", re.sub("corrino", "thorvald", s)) for s in mine]
    rules.append(",\n".join(new) + " {\n  " + body.replace("\n", "\n  ").replace("  \n", "\n") + "\n}\n")
    kept += 1
rules.append("faction-card > .box .portrait.Thorvald {\n  image: \"%s\" fit;\n}\n" % PORTRAIT)
rules.append("ai-faction-card > .box .portrait.Thorvald {\n  image: \"%s\" fit;\n}\n" % PORTRAIT)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8", newline="\n").write(
    "/* House Thorvald: generated by thorvald_councillors/08_scripts/31_faction_css.py from the vanilla UI/style.css */\n\n"
    + "\n".join(rules))
print("wrote %s: %d Corrino rules renamed, %d portrait rules replaced by Memnon's" % (OUT, kept, skipped))
